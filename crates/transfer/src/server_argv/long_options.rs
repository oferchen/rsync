//! The long options of 3.5.2's popt table, as a server's parse reads them.
//!
//! upstream: options.c:610-876 `long_options[]`. The server parses its argv
//! with this same table (options.c:1515), so a long option a client forwards
//! with `-M` / `--remote-option` (options.c:3251-3258, appended after every
//! other server argument) is accepted wherever the client would accept it.
//!
//! Left out, so the server still refuses them as unknown: `--help` and
//! `--version`, the daemon-mode switches (`--config`, `--daemon`, `--dparam`,
//! `--detach`, `--no-detach`, options.c:868-873), and the server-side
//! features oc does not implement (`--read-batch`, `--write-batch`,
//! `--copy-as`).

/// How the server's popt pass treats one long option.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LongOption {
    /// A switch without a value: read by the server's long-option pass, or
    /// one a server ignores.
    Flag,
    /// An option whose value is joined (`--opt=VALUE`) or the next token.
    Value,
    /// The long name of a short switch: the same popt entry, so it sets
    /// what the letter sets.
    Letter(char),
    /// The long name of a short option that takes a value.
    ValueLetter(char),
    /// A negation that resets what the short switch set.
    Clears(char),
}

impl LongOption {
    /// Whether popt binds a value to this option.
    #[must_use]
    pub const fn takes_value(self) -> bool {
        matches!(self, Self::Value | Self::ValueLetter(_))
    }
}

/// Looks up a long option by its name, without the leading `--` or any
/// `=VALUE`.
#[must_use]
pub fn long_option(name: &str) -> Option<LongOption> {
    LONG_OPTIONS
        .iter()
        .find(|(entry, _)| *entry == name)
        .map(|&(_, kind)| kind)
}

